import { useMemo, useState } from 'react'
import { Prism } from '../lib/prism'
import styles from './CodeView.module.css'

interface CodeViewProps {
  code: string
  language: string
  numbered?: boolean
  className?: string
}

function escapeHtml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

/**
 * Highlight one line at a time.
 *
 * Prism has no per-line mode, so a token that spans newlines (a block comment,
 * a template literal) is split across two highlights and its continuation line
 * loses colour. That is the honest trade for a gutter that always aligns and
 * for lines that can be rendered as real rows: the alternative, highlighting
 * the block and then splitting the markup, either misaligns the gutter or
 * breaks a tag in half.
 */
function highlightLine(line: string, language: string): string {
  if (!line) return ''
  const grammar = Prism.languages[language]
  if (!grammar || language === 'plain') return escapeHtml(line)
  try {
    return Prism.highlight(line, grammar, language)
  } catch {
    return escapeHtml(line)
  }
}

export function CodeView({ code, language, numbered = true, className }: CodeViewProps) {
  const [wrap, setWrap] = useState(false)

  const lines = useMemo(() => {
    const source = code.replace(/\t/g, '  ')
    return source.split('\n').map((line) => highlightLine(line, language))
  }, [code, language])

  const gutterWidth = `${String(lines.length).length + 1}ch`

  return (
    <div
      className={`${styles.view} ${className ?? ''}`}
      data-wrap={wrap ? 'on' : 'off'}
      style={{ ['--gutter' as string]: numbered ? gutterWidth : '0ch' }}
    >
      <div className={styles.scroller}>
        <div className={styles.rows}>
          {lines.map((html, index) => (
            <div key={index} className={styles.row}>
              {numbered ? (
                <span className={styles.num} aria-hidden="true">
                  {index + 1}
                </span>
              ) : null}
              <code
                className={`${styles.code} code-text`}
                // Markup is generated by Prism from escaped text above; the
                // entry itself is never inserted as HTML.
                dangerouslySetInnerHTML={{ __html: html || '\u200b' }}
              />
            </div>
          ))}
        </div>
      </div>
      <button
        type="button"
        className={styles.wrapToggle}
        onClick={() => setWrap((value) => !value)}
        aria-pressed={wrap}
        title={wrap ? 'Stop wrapping long lines' : 'Wrap long lines'}
      >
        {wrap ? 'no wrap' : 'wrap'}
      </button>
    </div>
  )
}
